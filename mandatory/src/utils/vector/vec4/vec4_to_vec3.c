#include "vector.h"

t_vec3	vec4_to_vec3(t_vec4 v)
{
	if (v.w == 0.0f)
		return (vec3(v.x, v.y, v.z));
	return (vec3_div(v.w, vec3(v.x, v.y, v.z)));
}
