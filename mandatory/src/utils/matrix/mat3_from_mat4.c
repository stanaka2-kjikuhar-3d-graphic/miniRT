#include "matrix.h"

/* Upper-left 3x3 (linear part) for normal transforms. */
t_mat3	mat3_from_mat4(t_mat4 const *m)
{
	return ((t_mat3){.m = {\
		{m->m[0][0], m->m[0][1], m->m[0][2]}, \
		{m->m[1][0], m->m[1][1], m->m[1][2]}, \
		{m->m[2][0], m->m[2][1], m->m[2][2]}, \
	}});
}
