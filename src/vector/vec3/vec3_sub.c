#include "vector.h"

t_dvec3	dvec3_sub(t_dvec3 a, t_dvec3 b)
{
	return ((t_dvec3){\
		.x = a.x - b.x, \
		.y = a.y - b.y, \
		.z = a.z - b.z \
	});
}
