#include "vector.h"

t_dvec3	dvec3_cross(t_dvec3 a, t_dvec3 b)
{
	return ((t_dvec3){\
		.x = a.y * b.z - a.z * b.y, \
		.y = a.z * b.x - a.x * b.z, \
		.z = a.x * b.y - a.y * b.x \
	});
}
