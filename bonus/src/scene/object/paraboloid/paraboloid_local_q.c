#include "matrix.h"

t_mat4	paraboloid_local_q(float a)
{
	t_mat4	q;

	q = mat4_identity();
	q.m[2][2] = 0.0f;
	q.m[3][3] = 0.0f;
	q.m[2][3] = -(a / 2.0f);
	q.m[3][2] = -(a / 2.0f);
	return (q);
}
