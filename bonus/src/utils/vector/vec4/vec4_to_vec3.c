#include "vector.h"

/*
** 点用の射影。w が 0（方向ベクトル）や 1 の場合はそのまま xyz を返す。
*/
t_vec3	vec4_to_vec3(t_vec4 v)
{
	if (v.w == 0.0f || v.w == 1.0f)
		return (vec3(v.x, v.y, v.z));
	return (vec3(v.x / v.w, v.y / v.w, v.z / v.w));
}
