float	average_rgb(unsigned int rgb)
{
	return ((float)(((rgb & 0xff) / 255.0) + (((rgb >> 8) & 0xff) / 255.0) \
				+ (((rgb >> 16) & 0xff) / 255.0)) / 3);
}
